OUTRO_HOLD = 4.0  # титры в конце, без речи

SAY = [
    (r"ППУ", "пэ-пэ-у"), (r"\bПС\b", "пэ-эс"), (r"Excel", "Э́ксель"), (r"\bLLM\b", "эл-эл-эм"),
    (r"bge-m3", "би-джи-и эм-три"), (r"Qwen", "Квен"), (r"см\. вложение", "смотри вложение"),
    (r" - ", ", "), (r"[«»]", ""),
]


def say(text: str) -> str:
    for a, b in SAY:
        text = re.sub(a, b, text)
    return text


def tts(text: str, out: Path):
    subprocess.run([str(HERE / "venv/bin/piper"), "-m", str(VOICE), "-f", str(out),
                    "--length-scale", str(SPEED), "--sentence-silence", "0.25"],
                   input=text.encode(), check=True, capture_output=True)


def duration(p: Path) -> float:
    with wave.open(str(p)) as w:
        return w.getnframes() / w.getframerate()


def srt_time(t: float) -> str:
    ms = round(t * 1000)
    return f"{ms // 3600000:02}:{ms // 60000 % 60:02}:{ms // 1000 % 60:02},{ms % 1000:03}"


def chunks(text: str, limit: int = 84) -> list[str]:
    """Длинную фразу - на куски по предложениям, затем по запятым и тире; тире остаётся в конце куска."""
    text = text.replace("см. ", "см.\u00a0")
    out = []
    for p in re.split(r"(?<=[.?!:]) +", text):
        while len(p) > limit:
            cuts = [m.end() for m in re.finditer(r",(?= )| -(?= )", p) if 30 < m.end() <= limit]
            cut = cuts[-1] if cuts else p.rfind(" ", 0, limit)
            out.append(p[:cut].strip())
            p = p[cut:].strip()
        if p:
            out.append(p)
    return [x.replace("\u00a0", " ") for x in out]


SHORT = {"и", "в", "во", "на", "с", "со", "к", "о", "а", "но", "та", "то", "же", "не", "по", "из", "за", "от", "до", "у", "это"}


def wrap2(s: str, width: int = 46) -> str:
    """Две строки примерно поровну; строка не начинается с тире и не кончается коротким словом."""
    if len(s) <= width:
        return s
    best, best_cost = None, 1e9
    for i, ch in enumerate(s):
        if ch != " ":
            continue
        a, b = s[:i], s[i + 1:]
        cost = abs(len(a) - len(b))
        if b.startswith("- ") or b.startswith("-"):
            cost += 40
        if a.split()[-1].lower().strip("«»,") in SHORT:
            cost += 25
        if max(len(a), len(b)) > width + 8:
            cost += 30
        if a.endswith((",", ":", ".")):
            cost -= 6
        if cost < best_cost:
            best, best_cost = i, cost
    return s[:best] + "\n" + s[best + 1:]


def main():
    (HERE / "audio").mkdir(exist_ok=True)
    (HERE / "out").mkdir(exist_ok=True)
    t, scenes, srt, concat = 0.0, [], [], []
    for sid, lead, beats in SCENES:
        s_start = t
        t += lead
        bl = []
        for k, text in enumerate(beats):
            spoken = say(text)
            key = hashlib.sha1(f"{SPEED}|{spoken}".encode()).hexdigest()[:12]
            wav = HERE / "audio" / f"{sid}_{k}_{key}.wav"
            if not wav.exists():
                tts(spoken, wav)
            d = duration(wav)
            bl.append({"t": round(t - s_start, 3), "d": round(d, 3), "text": text})
            concat.append((round(t, 3), wav))
            # субтитры: куски пропорционально длине
            pieces = chunks(text)
            total = sum(len(p) for p in pieces)
            ct = t
            for p in pieces:
                pd = d * len(p) / total
                srt.append((ct, ct + pd, wrap2(p)))
                ct += pd
            t += d + GAP
        t += SCENE_TAIL - GAP
        if sid == "outro":
            t += OUTRO_HOLD
        scenes.append({"id": sid, "start": round(s_start, 3), "dur": round(t - s_start, 3), "beats": bl})
        t = round(t, 3)
    timeline = {"total": round(t, 3), "scenes": scenes,
                "subs": [[round(a, 3), round(b, 3), txt] for a, b, txt in srt]}
    (HERE / "stage/timeline.js").write_text("window.TIMELINE = " + json.dumps(timeline, ensure_ascii=False, indent=1) + ";\n",
                                            encoding="utf-8")
    (HERE / "out/subs.srt").write_text("\n".join(f"{i}\n{srt_time(a)} --> {srt_time(b)}\n{txt}\n"
                                                 for i, (a, b, txt) in enumerate(srt, 1)), encoding="utf-8")
    (HERE / "audio/voice.json").write_text(json.dumps([(a, str(w)) for a, w in concat]), encoding="utf-8")
    for s in scenes:
        print(f"{s['id']:9} start {s['start']:7.1f}  dur {s['dur']:6.1f}  beats {len(s['beats'])}")
    print("total", round(t, 1), "s")


if __name__ == "__main__":
    main()
